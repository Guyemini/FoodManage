function RecipeCard({ dish, isOpen, onToggle }) {
  return (
    <div className="menu-dish-card">
      <div className="menu-dish-header">
        <div>
          <h4>{dish.name}</h4>
          <p className="dish-type">{dish.type}</p>
        </div>
        <button onClick={onToggle} className="recipe-toggle-btn">
          {isOpen ? 'הסתר מתכון' : 'הצג מתכון'}
        </button>
      </div>

      {isOpen && (
        <div className="recipe-details">
          <h5>מרכיבים</h5>
          <ul>
            {dish.ingredients.map((item, idx) => <li key={idx}>{item}</li>)}
          </ul>

          <h5>אופן הכנה</h5>
          <ol>
            {dish.steps.map((step, idx) => <li key={idx}>{step}</li>)}
          </ol>
        </div>
      )}
    </div>
  );
}

export default function Menus() {
  const [openMap, setOpenMap] = useState({});

  const toggleDish = (mealKey, dishIndex) => {
    const key = `${mealKey}-${dishIndex}`;
    setOpenMap(prev => ({ ...prev, [key]: !prev[key] }));
  };

  return (
    <div className="menus-page animate-fade-in">
      <div className="menus-grid">
        {Object.entries(MENU_DATA).map(([mealKey, meal]) => (
          <section key={mealKey} className="menu-column">
            <h3>{meal.emoji} {meal.title}</h3>
            {meal.dishes.map((dish, idx) => {
              const key = `${mealKey}-${idx}`;
              return (
                <RecipeCard
                  key={key}
                  dish={dish}
                  isOpen={!!openMap[key]}
                  onToggle={() => toggleDish(mealKey, idx)}
                />
              );
            })}
          </section>
        ))}
      </div>
    </div>
  );
}